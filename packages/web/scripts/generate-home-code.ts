import { writeFile } from "node:fs/promises";
import { codeToHtml } from "shiki";
import { featureExamples } from "./feature-examples";
import { installRaw, sourceExamples } from "./home-examples";

type Example = {
	file: string;
	language: string;
	raw: string;
	side?: string;
	tone?: string;
	/** 1-based line numbers to mark as the failure or success path. */
	lines?: { ok?: readonly number[]; err?: readonly number[] };
};

/** Generate highlighted code and copy text together, preventing documentation drift. */
async function generateHomeCode(): Promise<void> {
	const all: Record<string, Example> = {
		...sourceExamples,
		...featureExamples,
	};
	const entries = await Promise.all(
		Object.entries(all).map(async ([name, example]) => [
			name,
			{
				file: example.file,
				raw: example.raw,
				...(example.side ? { side: example.side } : {}),
				...(example.tone ? { tone: example.tone } : {}),
				html: await codeToHtml(example.raw, {
					lang: example.language,
					themes: { dark: "nord" },
					defaultColor: false,
					transformers: [
						{
							line(node, line) {
								if (example.lines?.err?.includes(line)) {
									this.addClassToHast(node, "is-err");
								}
								if (example.lines?.ok?.includes(line)) {
									this.addClassToHast(node, "is-ok");
								}
							},
						},
					],
				}),
			},
		]),
	);
	const content = `// Generated by scripts/generate-home-code.ts; edit scripts/home-examples.ts or scripts/feature-examples.ts.\nexport const installRaw = ${JSON.stringify(installRaw)};\nexport const examples = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`;
	await writeFile(new URL("../home-code-blocks.ts", import.meta.url), content);
}

await generateHomeCode();
