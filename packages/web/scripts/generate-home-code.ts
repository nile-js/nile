import { writeFile } from "node:fs/promises";
import { codeToHtml } from "shiki";
import { installRaw, sourceExamples } from "./home-examples";

/** Generate highlighted code and copy text together, preventing documentation drift. */
async function generateHomeCode(): Promise<void> {
	const entries = await Promise.all(
		Object.entries(sourceExamples).map(async ([name, example]) => [
			name,
			{
				file: example.file,
				raw: example.raw,
				html: await codeToHtml(example.raw, {
					lang: example.language,
					theme: "material-theme-ocean",
				}),
			},
		]),
	);
	const content = `// Generated by scripts/generate-home-code.ts; edit scripts/home-examples.ts.\nexport const installRaw = ${JSON.stringify(installRaw)};\nexport const examples = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`;
	await writeFile(new URL("../home-code-blocks.ts", import.meta.url), content);
}

await generateHomeCode();
